#!/usr/bin/env node
/**
 * Extracts the mps-gradle-plugin <-> MPS / Gradle / Java compatibility
 * contract from the plugin's and mps-build-backends' sources and writes the
 * `extracted` part of scripts/gradle-plugin-compat.json. The `curated` part
 * (facts that only exist as CHANGELOG prose) is kept as it is.
 *
 * Method, sources and the re-assessment runbook: docs/gradle-plugin-compat.md.
 *
 * Published versions carry their source commit as the last segment
 * (`1.31.0.1.1243113`, `1.27.4.239.aeb5185`); versions without one
 * (`1.32.0`) are found by their release tag (`mps-gradle-plugin-1.32.0`).
 * At that commit:
 *
 *   plugin    MPS_BUILD_BACKENDS_VERSION   backend range it resolves at build time
 *             BACKENDS_MIN/MAX_RELEASE     same, since 1.32.0 (BuildBackend.kt)
 *             gradle-wrapper.properties    Gradle it was built with
 *             build.gradle(.kts)           Java target
 *   backends  supportedMpsVersions         tested-against MPS list (gradle.properties,
 *             SUPPORTED_MPS_VERSIONS       since 2025-05; before: integration-tests/
 *                                          build.gradle.kts, since 2022-02)
 *
 * The launcher a plugin version pins comes from its POM (data/deps).
 *
 * Read-only: the repositories are cloned into a cache directory and
 * only read with `git show` / `git rev-parse`; nothing is built or executed.
 * Run after fetch-versions.mjs and fetch-deps.mjs.
 *
 * Usage: node scripts/extract-gradle-plugin-compat.mjs [--repos <dir>]
 */

import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { compareVersions, isSnapshot, isTool } from '../versions-lib.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = join(ROOT, 'scripts', 'gradle-plugin-compat.json');

const PLUGIN_SLUG = 'de.itemis.mps_mps-gradle-plugin';
const SOURCES = {
  plugin: 'https://github.com/mbeddr/mps-gradle-plugin.git',
  backends: 'https://github.com/mbeddr/mps-build-backends.git',
};

const COMMENT =
  'EXTRACTED, do not edit `extracted` by hand: it is regenerated by ' +
  'scripts/extract-gradle-plugin-compat.mjs from the sources of mbeddr/mps-gradle-plugin and ' +
  'mbeddr/mps-build-backends at the commit each published version was built from. The contract is ' +
  '"tested against": the MPS versions mps-build-backends runs its integration tests with. `curated` ' +
  'holds facts that exist only as CHANGELOG prose and is maintained following docs/gradle-plugin-compat.md.';

function parseArgs(argv) {
  const index = argv.indexOf('--repos');
  return { repos: index === -1 ? join(tmpdir(), 'mps-compat-sources') : argv[index + 1] };
}

function git(dir, ...args) {
  return execFileSync('git', ['-C', dir, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
}

/**
 * Full clone (both repositories are small; a blobless clone would fetch every
 * file read lazily, one round trip each), or fetch when it exists. All
 * branches: plugin 2.x lives on one.
 */
function syncRepo(url, dir) {
  if (existsSync(join(dir, '.git')) || existsSync(join(dir, 'HEAD'))) {
    git(dir, 'fetch', '--quiet', '--prune', 'origin', '+refs/heads/*:refs/remotes/origin/*', '+refs/tags/*:refs/tags/*');
  } else {
    execFileSync('git', ['clone', '--quiet', '--no-checkout', url, dir], { stdio: 'ignore' });
  }
}

const commitOf = (version) => version.split('.').at(-1).match(/^[0-9a-f]{7,40}$/)?.[0] ?? null;

function resolve(dir, ref) {
  try {
    return git(dir, 'rev-parse', '--verify', '--quiet', `${ref}^{commit}`).trim();
  } catch {
    return null;
  }
}

/**
 * Source commit of a published version: the hash it carries, else its
 * release tag. SNAPSHOTs have neither.
 */
function sourceCommit(dir, artifactId, version) {
  const hash = commitOf(version);
  if (hash) return resolve(dir, hash);
  if (isSnapshot(version)) return null;
  for (const tag of [`${artifactId}-${version}`, `v${version}`, version]) {
    const commit = resolve(dir, `refs/tags/${tag}`);
    if (commit) return commit;
  }
  return null;
}

function show(dir, commit, path) {
  try {
    return git(dir, 'show', `${commit}:${path}`);
  } catch {
    return null;
  }
}

function grepAt(dir, commit, pattern, ...paths) {
  try {
    return git(dir, 'grep', '-h', '-E', pattern, commit, '--', ...paths);
  } catch {
    return '';
  }
}

/** Tested-against MPS versions at one mps-build-backends commit, or null. */
function testedMps(dir, commit) {
  const properties = show(dir, commit, 'gradle.properties');
  const listed = properties?.match(/^supportedMpsVersions=(.*)$/m)?.[1];
  if (listed) return listed.split(',').map((v) => v.trim()).filter(Boolean);
  const build = show(dir, commit, 'integration-tests/build.gradle.kts');
  const array = build?.match(/SUPPORTED_MPS_VERSIONS\s*=\s*(?:arrayOf|listOf|setOf)\(([^)]*)\)/)?.[1];
  if (array) return [...array.matchAll(/"([^"]+)"/g)].map((m) => m[1]);
  return null;
}

/**
 * Backend range at one plugin commit: the `MPS_BUILD_BACKENDS_VERSION` range,
 * or since 1.32.0 `latest.release` bounded by BACKENDS_MIN_RELEASE (inclusive)
 * and BACKENDS_MAX_RELEASE (exclusive, prereleases rejected), as `[min,max)`.
 */
function backendsRange(dir, commit) {
  const legacy = grepAt(dir, commit, 'MPS_BUILD_BACKENDS_VERSION *=', '*.kt')
    .match(/MPS_BUILD_BACKENDS_VERSION\s*=\s*"([^"]+)"/)?.[1];
  if (legacy) return legacy;
  const bounds = grepAt(dir, commit, 'BACKENDS_(MIN|MAX)_RELEASE *=', '*.kt');
  const min = bounds.match(/BACKENDS_MIN_RELEASE\s*=\s*"([^"]+)"/)?.[1];
  const max = bounds.match(/BACKENDS_MAX_RELEASE\s*=\s*"([^"]+)"/)?.[1];
  return min && max ? `[${min},${max})` : null;
}

function pluginFacts(dir, commit) {
  const range = backendsRange(dir, commit);
  const gradle = show(dir, commit, 'gradle/wrapper/gradle-wrapper.properties')
    ?.match(/gradle-([0-9][0-9A-Za-z.\-]*?)-(?:bin|all)\.zip/)?.[1] ?? null;
  const build = (show(dir, commit, 'build.gradle.kts') ?? '') + (show(dir, commit, 'build.gradle') ?? '');
  const java =
    build.match(/JavaVersion\.VERSION_(?:1_)?(\d+)/)?.[1] ??
    build.match(/jvmTarget\s*=\s*"(?:1\.)?(\d+)"/)?.[1] ??
    show(dir, commit, '.java-version')?.trim().replace(/^1\./, '').split('.')[0] ??
    null;
  return { backendsRange: range, gradle, java };
}

async function readJson(path) {
  return existsSync(path) ? JSON.parse(await readFile(path, 'utf8')) : null;
}

const releases = (data) => data.lines.flatMap((line) => line.versions.map((entry) => entry.v));

async function main() {
  const { repos } = parseArgs(process.argv.slice(2));
  await mkdir(repos, { recursive: true });
  const dirs = { plugin: join(repos, 'mps-gradle-plugin'), backends: join(repos, 'mps-build-backends') };
  for (const [key, url] of Object.entries(SOURCES)) syncRepo(url, dirs[key]);

  const summary = await readJson(join(ROOT, 'versions.json'));
  if (!summary) throw new Error('versions.json missing -- run fetch-versions.mjs first');
  const pins = (await readJson(join(ROOT, 'data', 'deps', `${PLUGIN_SLUG}.json`)))?.versions ?? {};
  const unresolved = [];

  const plugin = {};
  const pluginData = await readJson(join(ROOT, 'data', `${PLUGIN_SLUG}.json`));
  for (const version of releases(pluginData).sort(compareVersions)) {
    const commit = sourceCommit(dirs.plugin, 'mps-gradle-plugin', version);
    if (!commit) unresolved.push(`mps-gradle-plugin ${version}`);
    const launcher = (pins[version] ?? []).find(([slug]) => slug === 'de.itemis.mps.build-backends_launcher')?.[1] ?? null;
    plugin[version] = {
      commit: commit?.slice(0, 12) ?? null,
      ...(commit ? pluginFacts(dirs.plugin, commit) : { backendsRange: null, gradle: null, java: null }),
      launcher,
    };
  }

  const backends = {};
  const testedCache = new Map();
  for (const library of summary.libraries.filter(isTool)) {
    if (library.groupId !== 'de.itemis.mps.build-backends') continue;
    const data = await readJson(join(ROOT, 'data', `${library.slug}.json`));
    if (!data) continue;
    const versions = {};
    for (const version of releases(data).sort(compareVersions)) {
      const commit = sourceCommit(dirs.backends, library.artifactId, version);
      if (!commit) unresolved.push(`${library.artifactId} ${version}`);
      if (commit && !testedCache.has(commit.slice(0, 12))) testedCache.set(commit.slice(0, 12), testedMps(dirs.backends, commit));
      versions[version] = commit?.slice(0, 12) ?? null;
    }
    backends[library.artifactId] = versions;
  }

  const previous = await readJson(OUTPUT);
  const payload = {
    $comment: COMMENT,
    contract: 'tested-against',
    method: 'docs/gradle-plugin-compat.md',
    sources: SOURCES,
    // backends: artifact -> version -> source commit; testedMps: commit -> MPS
    // versions mps-build-backends tested at that commit (null: no list there).
    extracted: { plugin, backends, testedMps: Object.fromEntries([...testedCache].sort()) },
    curated: previous?.curated ?? {},
  };
  const text = `${JSON.stringify(payload, null, 2)}\n`;
  const changed = !existsSync(OUTPUT) || (await readFile(OUTPUT, 'utf8')) !== text;
  if (changed) await writeFile(OUTPUT, text);

  const withoutTests = [...testedCache.values()].filter((list) => !list).length;
  process.stderr.write(
    `plugin versions ${Object.keys(plugin).length}, backend versions ` +
    `${Object.values(backends).reduce((n, v) => n + Object.keys(v).length, 0)}, ` +
    `unresolved commits ${unresolved.length}, backend commits without a tested list ${withoutTests}` +
    `${changed ? ', written' : ', unchanged'}\n`,
  );
  if (unresolved.length) process.stderr.write(`unresolved: ${unresolved.slice(0, 10).join('; ')}${unresolved.length > 10 ? ' ...' : ''}\n`);
}

main().catch((error) => {
  process.stderr.write(`${error.stack ?? error}\n`);
  process.exitCode = 1;
});
